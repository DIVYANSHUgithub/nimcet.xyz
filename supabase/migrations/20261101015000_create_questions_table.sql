
-- Phase 5 baseline: reproduce the existing production questions schema
-- for a clean local Supabase database.
-- This migration does not modify or copy production data.

CREATE TABLE public.questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam text NOT NULL DEFAULT 'NIMCET',
    exam_year integer NOT NULL,
    section text NOT NULL,
    question_number integer NOT NULL,
    question text NOT NULL,
    options jsonb NOT NULL,
    correct_option integer,
    explanation text,
    subject text,
    topic text,
    difficulty text,
    source text,
    status text NOT NULL DEFAULT 'published',
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT questions_status_check
        CHECK (status IN ('draft', 'published')),

    CONSTRAINT valid_correct_option
        CHECK (
            correct_option IS NULL
            OR correct_option BETWEEN 0 AND 3
        ),

    CONSTRAINT valid_options
        CHECK (
            jsonb_typeof(options) = 'array'
            AND jsonb_array_length(options) = 4
        ),

    CONSTRAINT unique_exam_question
        UNIQUE (exam, exam_year, section, question_number)
);

ALTER TABLE public.questions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public can read published questions"
    ON public.questions
    FOR SELECT
    TO anon, authenticated
    USING (status = 'published');

-- Match the existing production API privileges.
-- Frontend users can only read questions.
REVOKE ALL PRIVILEGES
ON TABLE public.questions
FROM anon, authenticated;

GRANT SELECT
ON TABLE public.questions
TO anon, authenticated;

-- Trusted backend has full access.
GRANT ALL PRIVILEGES
ON TABLE public.questions
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.questions_id_seq
TO service_role;
